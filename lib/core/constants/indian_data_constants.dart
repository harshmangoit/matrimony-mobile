  /// Gets list of cities for a given state string filtered by active language
  static List<String> getCitiesForState(String? stateName, [bool isHindi = false]) {
    if (stateName == null || stateName.trim().isEmpty) {
      return getAllPopularCities(isHindi);
    }
    
    final cleanState = stateName.trim().toLowerCase();
    
    for (var key in stateCityMap.keys) {
      final engKey = extractEnglish(key).toLowerCase();
      final hinKey = extractHindi(key).toLowerCase();
      final rawKey = key.toLowerCase();
      if (cleanState == engKey || cleanState == hinKey || cleanState == rawKey || rawKey.contains(cleanState) || cleanState.contains(engKey)) {
        return stateCityMap[key]!.map((c) => formatOption(c, isHindi)).toList();
      }
    }

    return getAllPopularCities(isHindi);
  }

  /// Fallback popular cities list across India
  static List<String> getAllPopularCities([bool isHindi = false]) {
    final List<String> all = [];
    for (var list in stateCityMap.values) {
      for (var item in list) {
        all.add(formatOption(item, isHindi));
      }
    }
    return all;
  }

