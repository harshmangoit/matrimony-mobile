  static String extractEnglish(String val) {
    if (val.contains('(')) {
      return val.split('(')[0].trim();
    }
    if (val.contains(' / ')) {
      return val.split(' / ')[0].trim();
    }
    return val.trim();
  }

  static String extractHindi(String val) {
    if (val.contains('(') && val.contains(')')) {
      final start = val.indexOf('(');
      final end = val.lastIndexOf(')');
      if (end > start) {
        return val.substring(start + 1, end).trim();
      }
    }
    if (val.contains(' / ')) {
      final parts = val.split(' / ');
      if (parts.length > 1) return parts[1].trim();
    }
    return val.trim();
  }

