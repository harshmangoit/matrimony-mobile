  static String formatValue(String? val, bool isHindi) {
    if (val == null || val.trim().isEmpty) return "";
    final trimmed = val.trim();

    if (trimmed.contains('(') || trimmed.contains(' / ')) {
      return isHindi ? extractHindi(trimmed) : extractEnglish(trimmed);
    }

    if (isHindi) {
      if (_englishToHindiMap.containsKey(trimmed)) {
        return _englishToHindiMap[trimmed]!;
      }
      for (var entry in _englishToHindiMap.entries) {
        if (trimmed == entry.key || trimmed.contains(entry.key)) {
          return entry.value;
        }
      }
    } else {
      if (_hindiToEnglishMap.containsKey(trimmed)) {
        return _hindiToEnglishMap[trimmed]!;
      }
      for (var entry in _hindiToEnglishMap.entries) {
        if (trimmed == entry.key || trimmed.contains(entry.key)) {
          return entry.value;
        }
      }
    }

    return trimmed;
  }

  static String formatOption(String val, bool isHindi) {
    return isHindi ? extractHindi(val) : extractEnglish(val);
  }

